function example_fetch_faarfield_mesh()
%EXAMPLE_FETCH_FAARFIELD_MESH Example client for the FAARFIELD mesh API.
%
% Before running this script, start:
%   website\faarfield-api\bin\x86\Release\FaarfieldApi.exe

addpath(fileparts(mfilename('fullpath')));

request = faasr3d.make_faarfield_mesh_request(struct( ...
    'layers', [ ...
        struct('type', 'AC overlay', 'h', 5.0, 'E', 400000,  'nu', 0.35) ...
        struct('type', 'PCC slab',   'h', 14.0, 'E', 4000000, 'nu', 0.15) ...
        struct('type', 'Base layer', 'h', 8.0, 'E', 50000,   'nu', 0.35) ...
    ], ...
    'subgrade', struct('E', 15000, 'nu', 0.40), ...
    'aircraft', struct('icao', 'B738', 'gear', 'D', 'mtow', 174200, ...
                       'name', 'B737-800', 'gearLoad', 0, ...
                       'nTires', 0, 'tirePressure', 200, 'tireSpacingIn', 0), ...
    'includeFullConnectivity', true, ...
    'includeStressField', false));

[result, meshData] = faasr3d.fetch_faarfield_mesh(request, struct( ...
    'baseUrl', 'http://localhost:5100', ...
    'saveJsonPath', fullfile(tempdir, 'faarfield_mesh_result.json')));

disp(result.computeTimeMs);
disp(size(meshData.surface.nodes));
disp(size(meshData.surface.tris));
disp(size(meshData.solver.nodes));
disp(size(meshData.solver.bricks));

faasr3d.plot_faarfield_mesh(meshData);

end
