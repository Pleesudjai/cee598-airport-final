function ipc = make_input_cards(overrides)
%MAKE_INPUT_CARDS Create a MATLAB struct equivalent to clsFEM.InputCards.

if nargin < 1 || isempty(overrides)
    overrides = struct();
end

ipc = struct( ...
    'nmmat', [], 'numnp', [], 'numelh', [], 'numsv', [], ...
    'inpsd', [], 'ntime', [], ...
    'nlcur', [], 'nptm', [], 'nload', [], 'numpc', [], ...
    'numdc', [], 'nrcc', [], ...
    'matype', [], 'den', [], 'prop', [], ...
    'idp', [], 'nob', [], 'x', [], 'ia', [], ...
    'nmmtde', [], 'nmelde', [], 'nmmass', [], ...
    'mtypde', [], 'ixde', [], 'cmde', [], 'sclf', [], ...
    'nrttlm', [], 'nrttls', [], ...
    'iparm', [], 'iaug', [], 'ifd', [], 'ngap', [], ...
    'irects', [], 'irectm', [], ...
    'fric', [], 'pend', [], 'altol', [], 'sfact', [], ...
    'tdeath', [], 'tbury', [], 'stfsf', [], ...
    'nod', [], 'idirn', [], 'ncur', [], 'npc', [], ...
    'nptst', [], 'itemp', [], 'itread', [], ...
    'fac', [], 'pld', [], 'tmode', [], 'cnwmk', [], ...
    'tbase', [], 'iacc', []);

names = fieldnames(overrides);
for k = 1:numel(names)
    ipc.(names{k}) = overrides.(names{k});
end
end
