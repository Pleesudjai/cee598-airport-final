function example_run()
%EXAMPLE_RUN Minimal demonstration of the translated FAASR package.

ipc = faasr3d.make_input_cards(struct( ...
    'nmmat', 0, 'numnp', 0, 'numelh', 0, 'numsv', 0, ...
    'inpsd', 0, 'ntime', 1, 'nlcur', 1, 'nptm', 2, ...
    'nload', 0, 'numpc', 0, 'numdc', 0, 'nrcc', 0, ...
    'ia', zeros(0, 1)));

opts = struct( ...
    'workingDir', fullfile(tempdir, 'faasr3d_demo'), ...
    'filenameOnly', 'demo_case', ...
    'modelOut', 1, ...
    'cleanupState', false, ...
    'inputiFn', @(state, ~) state, ...
    'intialFn', @(state) state, ...
    'solveFn', @local_solve_stub);

[stress1, stress8, state, runInfo] = faasr3d.faasr3d(ipc, opts);

disp(runInfo);
disp(stress1(1:5));
disp(stress8(1:5));
disp(state.WorkingDir);

end

function [state, stress1, stress8] = local_solve_stub(state, iStep, stress1, stress8, ~, ~)
stress1(iStep) = 100 + iStep;
stress8(iStep) = 10 + iStep;
state.stress1 = stress1;
state.stress8 = stress8;
end
