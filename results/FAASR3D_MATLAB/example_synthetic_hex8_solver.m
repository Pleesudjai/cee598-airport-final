function out = example_synthetic_hex8_solver()
%EXAMPLE_SYNTHETIC_HEX8_SOLVER Smoke test for the MATLAB HEX8 solver.

addpath(fileparts(mfilename('fullpath')));

meshData = struct();
meshData.layers = struct('id', 0, 'name', 'Test layer', 'zTop', 10, 'zBot', 0, 'thickness', 10);
meshData.solver = struct( ...
    'nodes', [ ...
         0  0  0; ...
        10  0  0; ...
        10 10  0; ...
         0 10  0; ...
         0  0 10; ...
        10  0 10; ...
        10 10 10; ...
         0 10 10], ...
    'bricks', [1 2 3 4 5 6 7 8], ...
    'layerIds', 0, ...
    'nodeBoundaryCodes', [7; 7; 7; 7; 0; 0; 0; 0], ...
    'loadNodeIds', [5; 6; 7; 8], ...
    'loadValues', -250 * ones(4, 1), ...
    'isHalfModel', false);

request = struct( ...
    'layers', struct('type', 'Test layer', 'h', 10, 'E', 4.0e6, 'nu', 0.20), ...
    'subgrade', struct('E', 15000, 'nu', 0.40));

model = faasr3d.build_pavement_fem_model(meshData, request);
results = faasr3d.solve_pavement_fem_model(model, struct('verbose', false));

assert(all(isfinite(results.displacements)), 'Displacement vector contains non-finite values.');
assert(results.summary.minUzIn < 0, 'Expected downward displacement under downward load.');

out = struct('model', model, 'results', results);
disp(out.results.summary);
end
